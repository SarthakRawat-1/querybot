BEGIN;
DROP TABLE IF EXISTS fines CASCADE;
DROP TABLE IF EXISTS reservations CASCADE;
DROP TABLE IF EXISTS loans CASCADE;
DROP TABLE IF EXISTS book_copies CASCADE;
DROP TABLE IF EXISTS books CASCADE;
DROP TABLE IF EXISTS publishers CASCADE;
DROP TABLE IF EXISTS authors CASCADE;
DROP TABLE IF EXISTS members CASCADE;
DROP TABLE IF EXISTS library_branches CASCADE;

CREATE TABLE library_branches (
 branch_id INTEGER PRIMARY KEY, branch_name VARCHAR(120) NOT NULL UNIQUE,
 city VARCHAR(80) NOT NULL, state_region VARCHAR(80) NOT NULL, opened_on DATE NOT NULL
);
CREATE TABLE members (
 member_id INTEGER PRIMARY KEY, first_name VARCHAR(60) NOT NULL, last_name VARCHAR(60) NOT NULL,
 email VARCHAR(160) NOT NULL UNIQUE,
 membership_tier VARCHAR(20) NOT NULL CHECK (membership_tier IN ('standard','student','premium','senior')),
 joined_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('active','expired','suspended')),
 home_branch_id INTEGER NOT NULL REFERENCES library_branches(branch_id)
);
CREATE TABLE authors (
 author_id INTEGER PRIMARY KEY, first_name VARCHAR(60) NOT NULL, last_name VARCHAR(60) NOT NULL,
 country VARCHAR(80) NOT NULL
);
CREATE TABLE publishers (
 publisher_id INTEGER PRIMARY KEY, publisher_name VARCHAR(140) NOT NULL UNIQUE, country VARCHAR(80) NOT NULL
);
CREATE TABLE books (
 book_id INTEGER PRIMARY KEY, isbn VARCHAR(24) NOT NULL UNIQUE, title VARCHAR(180) NOT NULL,
 author_id INTEGER NOT NULL REFERENCES authors(author_id),
 publisher_id INTEGER NOT NULL REFERENCES publishers(publisher_id), genre VARCHAR(60) NOT NULL,
 publication_year INTEGER NOT NULL CHECK (publication_year BETWEEN 1900 AND 2026),
 list_price NUMERIC(8,2) NOT NULL CHECK (list_price >= 0), language VARCHAR(40) NOT NULL DEFAULT 'English'
);
CREATE TABLE book_copies (
 copy_id INTEGER PRIMARY KEY, book_id INTEGER NOT NULL REFERENCES books(book_id),
 branch_id INTEGER NOT NULL REFERENCES library_branches(branch_id), barcode VARCHAR(30) NOT NULL UNIQUE,
 condition VARCHAR(20) NOT NULL CHECK (condition IN ('excellent','good','fair','damaged')),
 acquisition_date DATE NOT NULL,
 availability_status VARCHAR(20) NOT NULL CHECK (availability_status IN ('available','loaned','reserved','repair','lost'))
);
CREATE TABLE loans (
 loan_id INTEGER PRIMARY KEY, copy_id INTEGER NOT NULL REFERENCES book_copies(copy_id),
 member_id INTEGER NOT NULL REFERENCES members(member_id),
 checkout_branch_id INTEGER NOT NULL REFERENCES library_branches(branch_id),
 checkout_at TIMESTAMP NOT NULL, due_at TIMESTAMP NOT NULL, returned_at TIMESTAMP,
 status VARCHAR(20) NOT NULL CHECK (status IN ('open','returned','overdue','lost')),
 CHECK (due_at > checkout_at)
);
CREATE TABLE reservations (
 reservation_id INTEGER PRIMARY KEY, book_id INTEGER NOT NULL REFERENCES books(book_id),
 member_id INTEGER NOT NULL REFERENCES members(member_id),
 branch_id INTEGER NOT NULL REFERENCES library_branches(branch_id),
 requested_at TIMESTAMP NOT NULL, expires_at TIMESTAMP NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('queued','fulfilled','cancelled','expired')),
 CHECK (expires_at > requested_at)
);
CREATE TABLE fines (
 fine_id INTEGER PRIMARY KEY, loan_id INTEGER NOT NULL REFERENCES loans(loan_id),
 amount NUMERIC(8,2) NOT NULL CHECK (amount > 0), reason VARCHAR(100) NOT NULL,
 assessed_at TIMESTAMP NOT NULL, paid_at TIMESTAMP,
 status VARCHAR(20) NOT NULL CHECK (status IN ('unpaid','paid','waived','disputed'))
);



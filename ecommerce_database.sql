CREATE TABLE users (
    user_id         INTEGER PRIMARY KEY,
    first_name      VARCHAR(60) NOT NULL,
    last_name       VARCHAR(60) NOT NULL,
    email           VARCHAR(160) NOT NULL UNIQUE,
    phone           VARCHAR(30),
    password_hash   VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    status          VARCHAR(20) NOT NULL CHECK (status IN ('active','inactive','suspended')),
    marketing_opt_in BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE addresses (
    address_id      INTEGER PRIMARY KEY,
    user_id         INTEGER NOT NULL REFERENCES users(user_id),
    address_type    VARCHAR(20) NOT NULL CHECK (address_type IN ('shipping','billing','both')),
    line1           VARCHAR(160) NOT NULL,
    line2           VARCHAR(160),
    city            VARCHAR(80) NOT NULL,
    state_region    VARCHAR(80) NOT NULL,
    postal_code     VARCHAR(20) NOT NULL,
    country         VARCHAR(80) NOT NULL,
    is_default      BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE categories (
    category_id     INTEGER PRIMARY KEY,
    category_name   VARCHAR(100) NOT NULL UNIQUE,
    description     TEXT
);

CREATE TABLE products (
    product_id      INTEGER PRIMARY KEY,
    category_id     INTEGER NOT NULL REFERENCES categories(category_id),
    sku             VARCHAR(40) NOT NULL UNIQUE,
    product_name    VARCHAR(160) NOT NULL,
    description     TEXT,
    unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    stock_quantity  INTEGER NOT NULL CHECK (stock_quantity >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL
);

CREATE TABLE orders (
    order_id            INTEGER PRIMARY KEY,
    user_id             INTEGER NOT NULL REFERENCES users(user_id),
    shipping_address_id INTEGER NOT NULL REFERENCES addresses(address_id),
    billing_address_id  INTEGER NOT NULL REFERENCES addresses(address_id),
    order_number        VARCHAR(30) NOT NULL UNIQUE,
    order_date          TIMESTAMP NOT NULL,
    status              VARCHAR(20) NOT NULL CHECK (status IN ('pending','processing','shipped','delivered','cancelled','refunded')),
    subtotal            NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    shipping_fee        NUMERIC(10,2) NOT NULL CHECK (shipping_fee >= 0),
    tax_amount          NUMERIC(10,2) NOT NULL CHECK (tax_amount >= 0),
    discount_amount     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount        NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    currency            CHAR(3) NOT NULL DEFAULT 'INR'
);

CREATE TABLE order_items (
    order_item_id   INTEGER PRIMARY KEY,
    order_id        INTEGER NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id      INTEGER NOT NULL REFERENCES products(product_id),
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    line_total      NUMERIC(10,2) NOT NULL CHECK (line_total >= 0),
    UNIQUE(order_id, product_id)
);

CREATE TABLE carts (
    cart_id         INTEGER PRIMARY KEY,
    user_id         INTEGER NOT NULL UNIQUE REFERENCES users(user_id),
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL,
    status          VARCHAR(20) NOT NULL CHECK (status IN ('active','converted','abandoned'))
);

CREATE TABLE cart_items (
    cart_item_id    INTEGER PRIMARY KEY,
    cart_id         INTEGER NOT NULL REFERENCES carts(cart_id) ON DELETE CASCADE,
    product_id      INTEGER NOT NULL REFERENCES products(product_id),
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    added_at        TIMESTAMP NOT NULL,
    UNIQUE(cart_id, product_id)
);

CREATE TABLE transactions (
    transaction_id  INTEGER PRIMARY KEY,
    order_id        INTEGER NOT NULL REFERENCES orders(order_id),
    transaction_ref VARCHAR(50) NOT NULL UNIQUE,
    transaction_date TIMESTAMP NOT NULL,
    payment_method  VARCHAR(30) NOT NULL CHECK (payment_method IN ('upi','credit_card','debit_card','net_banking','wallet','cod')),
    provider        VARCHAR(60) NOT NULL,
    amount          NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    currency        CHAR(3) NOT NULL DEFAULT 'INR',
    status          VARCHAR(20) NOT NULL CHECK (status IN ('successful','failed','pending','refunded')),
    is_test_data    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE refunds (
    refund_id       INTEGER PRIMARY KEY,
    transaction_id  INTEGER NOT NULL REFERENCES transactions(transaction_id),
    refund_ref      VARCHAR(50) NOT NULL UNIQUE,
    refund_date     TIMESTAMP NOT NULL,
    amount          NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    reason          VARCHAR(120) NOT NULL,
    status          VARCHAR(20) NOT NULL CHECK (status IN ('requested','approved','processed','rejected'))
);

CREATE TABLE product_reviews (
    review_id       INTEGER PRIMARY KEY,
    user_id         INTEGER NOT NULL REFERENCES users(user_id),
    product_id      INTEGER NOT NULL REFERENCES products(product_id),
    rating          SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_title    VARCHAR(120),
    review_text     TEXT,
    created_at      TIMESTAMP NOT NULL,
    UNIQUE(user_id, product_id)
);


